
s1 = input("دخل يسطا ام القيمه الاوله ومتزهقنيش :")
s2 = input("خلاص متزعلش مش هتعصب عليك تاني دخل القيمه التانايه بقي :")

if len(s1) < len(s2):
    print(-1)
    print("الكلمه الاوله اقل من الكلمه التانيه")     
elif len(s1) > len(s2):
    print(1)
    print("الكلمه الاوله اكبر من الكلمه التانيه")
else:
    print(0)
    print("الكلام ال انت مدخله شبه بعضه يسطا")


